import { useEffect, useState } from "react";

import {
    getLabTests,
} from "../../services/laboratoryService";

function LabTests() {
    const [tests, setTests] = useState([]);
    const [search, setSearch] = useState("");

    const [loading, setLoading] = useState(true);
    const [error, setError] = useState("");

    useEffect(() => {
        const loadTests = async () => {
            try {
                setLoading(true);
                setError("");

                const response = await getLabTests();

                const data = Array.isArray(response?.data)
                    ? response.data
                    : response?.data?.results || [];

                // Show only active laboratory tests.
                // Test IDs are generated by Django backend.
                const activeTests = data.filter(
                    (test) =>
                        !test.status ||
                        test.status === "Active"
                );

                setTests(activeTests);
            } catch (error) {
                console.error(
                    "Error loading laboratory tests:",
                    error
                );

                setError(
                    error?.response?.data?.detail ||
                    "Unable to load laboratory tests."
                );

                setTests([]);
            } finally {
                setLoading(false);
            }
        };

        loadTests();
    }, []);

    const searchValue = search.trim().toLowerCase();

    const filteredTests = tests.filter((test) => {
        const testId =
            test?.test_id?.toString().toLowerCase() || "";

        const testName =
            test?.name?.toString().toLowerCase() || "";

        const description =
            test?.description?.toString().toLowerCase() || "";

        return (
            testId.includes(searchValue) ||
            testName.includes(searchValue) ||
            description.includes(searchValue)
        );
    });

    if (loading) {
        return (
            <div className="laboratory-page">
                <div className="loading-state">
                    Loading laboratory tests...
                </div>
            </div>
        );
    }

    return (
        <div className="laboratory-page">

            {/* PAGE HEADER */}
            <div className="page-header">

                <div>
                    <h1>
                        Lab Tests
                    </h1>

                    <p>
                        View available laboratory tests
                        and their charges.
                    </p>
                </div>

            </div>

            {/* ERROR */}
            {error && (
                <div className="alert alert-error">
                    {error}
                </div>
            )}

            {/* TEST CARD */}
            <div className="content-card">

                {/* CARD HEADER */}
                <div className="card-header">

                    <div>
                        <h2>
                            Available Tests
                        </h2>

                        <p>
                            Laboratory tests configured
                            by the administrator.
                        </p>
                    </div>

                    <span className="record-count">
                        {filteredTests.length} Tests
                    </span>

                </div>

                {/* SEARCH */}
                <div className="search-wrapper">

                    <input
                        type="text"
                        className="search-input"
                        placeholder="Search tests..."
                        value={search}
                        onChange={(event) =>
                            setSearch(event.target.value)
                        }
                    />

                </div>

                {/* TABLE */}
                <div className="table-container">

                    <table className="laboratory-table">

                        <thead>
                            <tr>
                                <th>
                                    Test ID
                                </th>

                                <th>
                                    Test Name
                                </th>

                                <th>
                                    Description
                                </th>

                                <th>
                                    Price
                                </th>

                                <th>
                                    Status
                                </th>
                            </tr>
                        </thead>

                        <tbody>

                            {filteredTests.length === 0 ? (

                                <tr>
                                    <td
                                        colSpan="5"
                                        className="empty-state"
                                    >
                                        {searchValue
                                            ? "No laboratory tests match your search."
                                            : "No active laboratory tests found."}
                                    </td>
                                </tr>

                            ) : (

                                filteredTests.map((test) => (

                                    <tr
                                        key={test.id}
                                    >

                                        {/* TEST ID */}
                                        <td>
                                            <span className="request-id">
                                                {test.test_id || "N/A"}
                                            </span>
                                        </td>

                                        {/* TEST NAME */}
                                        <td>
                                            <strong>
                                                {test.name || "N/A"}
                                            </strong>
                                        </td>

                                        {/* DESCRIPTION */}
                                        <td>
                                            {test.description || "—"}
                                        </td>

                                        {/* PRICE */}
                                        <td>
                                            ₹
                                            {Number(
                                                test.price || 0
                                            ).toFixed(2)}
                                        </td>

                                        {/* STATUS */}
                                        <td>
                                            <span
                                                className="status completed"
                                            >
                                                {test.status || "Active"}
                                            </span>
                                        </td>

                                    </tr>

                                ))

                            )}

                        </tbody>

                    </table>

                </div>

            </div>

        </div>
    );
}

export default LabTests;